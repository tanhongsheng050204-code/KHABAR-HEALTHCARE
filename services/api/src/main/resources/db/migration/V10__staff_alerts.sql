-- A clinic's staff chat for alerts and the morning briefing, and a log of every message sent to it.
-- Neither table holds a patient's name or words.
create table staff_channel (
    clinic_id uuid not null primary key,
    chat_enc varchar(512),
    linked_at timestamp(6) with time zone,
    linked_by uuid,
    alerts_on boolean not null,
    briefing_hour integer,
    link_code_hash varchar(64),
    link_code_expires_at timestamp(6) with time zone,
    link_code_by uuid,
    last_signature varchar(100),
    last_alert_at timestamp(6) with time zone,
    last_urgent integer not null,
    last_briefing_date date,
    constraint fk_staff_channel_clinic foreign key (clinic_id) references clinic
);

create table staff_alert_log (
    id bigint generated by default as identity,
    clinic_id uuid not null,
    kind varchar(20) not null,
    outcome varchar(20) not null,
    text varchar(2000) not null,
    detail varchar(500),
    at timestamp(6) with time zone not null,
    primary key (id)
);
create index ix_staff_alert_log_clinic on staff_alert_log (clinic_id);
