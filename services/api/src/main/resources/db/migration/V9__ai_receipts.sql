-- "What the AI saw": one row each time patient-related content left the clinical API for the AI service.
create table ai_receipt (
    id bigint generated by default as identity,
    patient_id uuid not null,
    purpose varchar(40) not null,
    endpoint varchar(100) not null,
    sent_enc varchar(16384) not null,
    truncated boolean not null,
    media boolean not null,
    names_removed integer not null,
    ics_removed integer not null,
    phones_removed integer not null,
    at timestamp(6) with time zone not null,
    primary key (id)
);
create index ix_ai_receipt_patient on ai_receipt (patient_id);
